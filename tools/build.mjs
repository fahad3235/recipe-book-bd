// Build: compiles tools/src/*.mjs into data/<category>.json + js/recipes-data.js
// Run: node tools/build.mjs   (from the project root)
import { writeFileSync, mkdirSync } from "node:fs";
import { ING } from "./src/ing.mjs";
import { STEPS } from "./src/steps.mjs";
import { DISHES as D1 } from "./src/dishes-1.mjs";
import { DISHES as D2 } from "./src/dishes-2.mjs";
import { DISHES as D3 } from "./src/dishes-3.mjs";
import { DISHES as D4 } from "./src/dishes-4.mjs";
import { DISHES as D5 } from "./src/dishes-5.mjs";

export const CATS = {
  "fish-curry": { en: "Fish Curry", bn: "মাছের তরকারি" },
  "bhorta":     { en: "Bhorta", bn: "ভর্তা" },
  "pitha":      { en: "Pitha", bn: "পিঠা" },
  "biryani":    { en: "Biryani & Khichuri", bn: "বিরিয়ানি ও খিচুড়ি" },
  "meat-curry": { en: "Meat Curry", bn: "মাংসের তরকারি" },
  "dal":        { en: "Dal", bn: "ডাল" },
  "vegetable":  { en: "Vegetables", bn: "সবজি" },
  "sweets":     { en: "Sweets", bn: "মিষ্টি" },
  "snacks":     { en: "Snacks", bn: "নাস্তা" },
  "pickles":    { en: "Pickles", bn: "আচার" },
};

const BN_D = { 0:"০", 1:"১", 2:"২", 3:"৩", 4:"৪", 5:"৫", 6:"৬", 7:"৭", 8:"৮", 9:"৯" };
const UNITS = [
  ["tbsp", "টেবিল চামচ"], ["tsp", "চা চামচ"], ["cups", "কাপ"], ["cup", "কাপ"],
  ["pcs", "টি"], ["bunch", "আঁটি"], ["kg", "কেজি"], ["ml", "মিলিলিটার"], ["L", "লিটার"], ["g", "গ্রাম"],
];
const PHRASES = { "to taste": "স্বাদমতো", "as needed": "পরিমাণমতো" };

function qtyBn(q) {
  if (PHRASES[q]) return PHRASES[q];
  let s = q.replace(/[0-9]/g, (d) => BN_D[d]);
  for (const [en, bn] of UNITS) {
    s = s.replace(new RegExp(`\\b${en}\\b`, "g"), bn);
  }
  return s;
}

const DISHES = [...D1, ...D2, ...D3, ...D4, ...D5];

function buildRecipe(d) {
  if (!CATS[d.cat]) throw new Error(`unknown category ${d.cat} in ${d.id}`);
  const main = ING[d.main];
  if (!main) throw new Error(`unknown ingredient key ${d.main} in ${d.id}`);
  const tpl = STEPS[d.steps];
  if (!tpl) throw new Error(`unknown steps template ${d.steps} in ${d.id}`);
  const sub = (s) => s.replaceAll("{M}", main.en).replaceAll("{MB}", main.bn);
  const ingredients = d.ings.map(([key, qty]) => {
    const ing = ING[key];
    if (!ing) throw new Error(`unknown ingredient key ${key} in ${d.id}`);
    return { en: ing.en, bn: ing.bn, qty, qtyBn: qtyBn(qty) };
  });
  return {
    id: d.id,
    cat: d.cat,
    name: { en: d.en, bn: d.bn },
    ingredients,
    steps: { en: tpl.en.map(sub), bn: tpl.bn.map(sub) },
    time: d.time,
    servings: d.servings,
    diff: d.diff,
  };
}

const recipes = DISHES.map(buildRecipe);

mkdirSync("data", { recursive: true });
mkdirSync("js", { recursive: true });

const byCat = {};
for (const r of recipes) {
  (byCat[r.cat] ||= []).push(r);
}
for (const [cat, list] of Object.entries(byCat)) {
  writeFileSync(`data/${cat}.json`, JSON.stringify(list, null, 2) + "\n");
}
const counts = Object.fromEntries(Object.entries(byCat).map(([c, l]) => [c, l.length]));
writeFileSync("data/index.json", JSON.stringify({ categories: CATS, counts, total: recipes.length }, null, 2) + "\n");
writeFileSync(
  "js/recipes-data.js",
  `// GENERATED by tools/build.mjs — do not edit by hand.\nwindow.RECIPES = ${JSON.stringify(recipes)};\nwindow.RB_CATS = ${JSON.stringify(CATS)};\n`
);

console.log(`Built ${recipes.length} recipes across ${Object.keys(byCat).length} categories:`);
for (const [c, n] of Object.entries(counts)) console.log(`  ${c}: ${n}`);
